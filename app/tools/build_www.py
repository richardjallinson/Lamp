#!/usr/bin/env python3
"""Copy the level data and finished pictures into the web app.

  python3 app/tools/build_www.py          (run from the repository root)

Reads  content/out/levels.json and images/lamp-NNN-id.jpg
Writes app/www/js/levels.js and app/www/img/*.jpg
The data is a plain script (window.LAMP_DATA = ...) because a web view inside an
iPhone app may refuse to fetch() local JSON files.
"""
import json
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
WWW = os.path.join(ROOT, "app", "www")
sys.path.insert(0, os.path.join(ROOT, "content", "tools"))
from lamp_levels import BOOKS  # noqa: E402

data = json.load(open(os.path.join(ROOT, "content", "out", "levels.json"), encoding="utf-8"))
img_src = os.path.join(ROOT, "images")
img_dst = os.path.join(WWW, "img")
os.makedirs(img_dst, exist_ok=True)
for f in os.listdir(img_dst):
    if f.endswith(".jpg"):
        os.remove(os.path.join(img_dst, f))
have = {}
for f in sorted(os.listdir(img_src)):
    m = re.match(r"lamp-(\d{3})-([a-z]+)\.jpg$", f)
    if m:
        shutil.copy(os.path.join(img_src, f), os.path.join(img_dst, f))
        have[m.group(2)] = f

stories = []
for s in data["stories"]:
    levels = []
    for lv in s["levels"]:
        out = {"id": lv["id"], "v": lv["v"]}
        if lv.get("recall"):
            out.update(recall=True, start=lv["from"])
        else:
            out.update(wheel=lv["wheel"], hide=lv["hide"], bonus=lv["bonus"])
        if lv.get("tip"):
            out["tip"] = lv["tip"]
        levels.append(out)
    stories.append({
        "n": s["n"], "id": s["id"], "title": s["title"], "book": s["book"], "free": s["free"],
        "key": s["key"], "note": s["note"], "img": have.get(s["id"]),
        "verses": [{"ref": v["display"], "w": v["words"]} for v in s["verses"]],
        "levels": levels,
    })
daily = [{"ref": d["display"], "w": d["words"], "wheel": d["wheel"], "hide": d["hide"],
          "bonus": d["bonus"], "story": d["story"]} for d in data["daily"]]
payload = {"version": 1, "translation": "KJV", "books": BOOKS, "stories": stories, "daily": daily}
js = "/* generated by app/tools/build_www.py from content/out/levels.json; do not edit */\nwindow.LAMP_DATA=" + \
     json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n"
open(os.path.join(WWW, "js", "levels.js"), "w", encoding="utf-8").write(js)
# the Lamplighter's narration (processed files from audio/narration/)
aud_src, aud_dst = os.path.join(ROOT, "audio", "narration"), os.path.join(WWW, "audio", "narration")
if os.path.isdir(aud_src):
    os.makedirs(aud_dst, exist_ok=True)
    for f in os.listdir(aud_src):
        if f.endswith(".mp3"):
            shutil.copy(os.path.join(aud_src, f), os.path.join(aud_dst, f))
print(f"levels.js {len(js)//1024} KB · {len(stories)} stories · {sum(len(s['levels']) for s in stories)} levels · "
      f"{len(daily)} daily · {len(have)} pictures")
